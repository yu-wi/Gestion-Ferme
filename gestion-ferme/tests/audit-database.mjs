// Test PostgreSQL isolé. Voir supabase/README.md pour l'installation de PGlite hors du dépôt.
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
const modulePath = process.env.PGLITE_MODULE_PATH;
if (!modulePath) throw new Error('Définissez PGLITE_MODULE_PATH vers @electric-sql/pglite/dist/index.js (installation de test hors dépôt).');
const { PGlite } = await import(pathToFileURL(modulePath).href);
const db = new PGlite();
const admin = '00000000-0000-0000-0000-000000000001';
const user = '00000000-0000-0000-0000-000000000002';
const lot = '00000000-0000-0000-0000-000000000003';
const charge = '00000000-0000-0000-0000-000000000004';
await db.exec(`
 create schema auth;
 create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
 create role anon; create role authenticated;
 grant usage on schema auth, public to anon, authenticated;
 create table app_profiles(user_id uuid primary key, username text, display_name text, role text, is_active boolean);
 insert into app_profiles values ('${admin}','admin','Administratrice','admin',true),('${user}','user','Éleveur','user',true);
 alter table app_profiles enable row level security;
 create policy own_profile on app_profiles for select to authenticated using (user_id=auth.uid());
 grant select on app_profiles to authenticated;
 create table lots_volailles(id uuid primary key, nom text, quantite integer, is_active boolean);
 insert into lots_volailles values ('${lot}','3126',1800,false);
 create table charges(id uuid primary key default gen_random_uuid(),lot_id uuid,lot_nom text,type_charge text,montant numeric,updated_at timestamptz default now());
 create table app_settings(key text primary key,value text,category text,updated_at timestamptz default now());
 grant select,insert,update,delete on charges,lots_volailles,app_settings to authenticated;
`);
const migration = await readFile(new URL('../supabase/journal-modifications.sql', import.meta.url), 'utf8');
await db.exec(migration);
await db.exec(migration); // Réexécution sans duplication des déclencheurs ni effacement des événements.
const scalar = async sql => (await db.query(sql)).rows[0];
const role = async id => { await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]); await db.exec('set role authenticated'); };
await role(admin);
await db.exec(`insert into charges(id,lot_id,lot_nom,type_charge,montant) values ('${charge}','${lot}','3126','ramassage',100);`);
await db.exec(`update charges set montant=120 where id='${charge}';`);
let events = (await db.query("select * from audit_events where table_name='charges' order by occurred_at")).rows;
assert.equal(events.length,2); assert.equal(events[0].operation,'INSERT'); assert.equal(events[0].old_values,null);
assert.equal(events[1].old_values.montant,100); assert.equal(events[1].new_values.montant,120);
assert.equal(events[1].actor_id,admin);assert.equal(events[1].actor_label,'Administratrice');assert.equal(events[1].lot_label,'3126');
await db.exec(`update charges set updated_at=now()+interval '1 day' where id='${charge}';`);
assert.equal((await scalar('select count(*)::int as n from audit_events')).n,2);
await db.exec(`begin;update charges set montant=999 where id='${charge}';rollback;`);
assert.equal((await scalar('select count(*)::int as n from audit_events')).n,2);
assert.equal(Number((await scalar(`select montant from charges where id='${charge}'`)).montant),120);
await db.exec(`delete from charges where id='${charge}';`);
events=(await db.query("select * from audit_events where operation='DELETE'")).rows;
assert.equal(events[0].old_values.montant,120);assert.equal(events[0].new_values,null);
for(const sql of ["delete from audit_events", "update audit_events set actor_label='faux'", "insert into audit_events(actor_label,table_name,operation) values ('faux','charges','INSERT')"]){ await assert.rejects(db.exec(sql),/permission denied/i); }
await role(user);
await db.exec(`insert into charges(lot_id,type_charge,montant) values ('${lot}','livraison',90);`);
assert.equal((await scalar('select count(*)::int as n from audit_events')).n,0);
await role(admin);
assert.equal((await scalar("select count(*)::int as n from audit_events where actor_label='Éleveur'")).n,1);
await db.exec("insert into app_settings values ('private_token','DO_NOT_LOG_TEST_VALUE','general',now());");
assert.equal((await scalar("select count(*)::int as n from audit_events where table_name='app_settings'")).n,0);
await db.exec("insert into app_settings values ('untracked_key','DO_NOT_LOG_TEST_VALUE',null,now());");
assert.equal((await scalar("select count(*)::int as n from audit_events where table_name='app_settings'")).n,0);
await db.exec("update app_settings set key='poultry_transport_price_ht',value='100' where key='private_token';");
const renamed = await scalar("select old_values,new_values from audit_events where table_name='app_settings'");
assert.equal(renamed.old_values,null);assert.equal(renamed.new_values.value,'100');
await db.exec(`insert into app_settings values ('lot_tariffs:${lot}','{}','lot_tariffs',now());`);
assert.equal((await scalar("select lot_id from audit_events where table_name='app_settings' and lot_id is not null")).lot_id,lot);
await db.exec('reset role');
await db.exec(`update app_profiles set is_active=false where user_id='${admin}';`);
await role(admin);
assert.equal((await scalar('select count(*)::int as n from audit_events')).n,0);
await db.exec('reset role');await db.exec(`update app_profiles set is_active=true where user_id='${admin}';`);
await db.exec('set role anon');await assert.rejects(db.query('select * from audit_events'),/permission denied/i);await db.exec('reset role');
await db.query("select set_config('request.jwt.claim.sub','',false)");
await db.exec(`update lots_volailles set quantite=1900 where id='${lot}';`);
assert.equal((await scalar("select actor_label from audit_events where table_name='lots_volailles'")).actor_label,'Opération système / SQL');
// Un échec d'écriture du journal annule également l'écriture métier.
await db.exec("alter table audit_events add constraint reject_audit_test check (false) not valid;");
await assert.rejects(db.exec(`update lots_volailles set quantite=9999 where id='${lot}';`));
assert.equal((await scalar(`select quantite from lots_volailles where id='${lot}'`)).quantite,1900);
await db.exec('alter table audit_events drop constraint reject_audit_test');
assert.equal((await scalar("select count(*)::int as n from audit_events where coalesce(old_values::text,'') || coalesce(new_values::text,'') like '%DO_NOT_LOG_TEST_VALUE%'")).n,0);
await db.close();
console.log('PostgreSQL isolé : déclencheurs INSERT/UPDATE/DELETE, auteur fiable, valeurs avant/après, réexécution, rollback, refus des écritures clientes, lecture admin actif uniquement, anonymes exclus, paramètres non suivis exclus, contexte des tarifs figés et atomicité vérifiés.');
